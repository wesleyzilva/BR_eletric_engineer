const applyTranslation = (lang) => {
  const elements = document.querySelectorAll('[data-translate]');
  elements.forEach((element) => {
    const key = element.getAttribute('data-translate');
    if (translations[lang] && translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });
};

const getLangFromHash = () => {
  const hash = window.location.hash.toLowerCase();
  if (hash === '#pt' || hash === '#pt-br') return 'pt';
  if (hash === '#en' || hash === '#en-us') return 'en';
  return null;
};

const initLanguageSwitcher = () => {
  const buttons = document.querySelectorAll('[data-lang-btn]');
  buttons.forEach((button) => {
    button.addEventListener('click', () => {
      const lang = button.getAttribute('data-lang-btn');
      window.location.hash = lang;
      applyTranslation(lang);
      updateActiveButton(lang);
    });
  });

  const hashLang = getLangFromHash();
  const initialLang = hashLang || 'en';
  if (!window.location.hash) {
    window.location.replace(`${window.location.pathname}#en`);
  }
  applyTranslation(initialLang);
  updateActiveButton(initialLang);

  window.addEventListener('hashchange', () => {
    const newLang = getLangFromHash() || 'en';
    applyTranslation(newLang);
    updateActiveButton(newLang);
  });
};

const updateActiveButton = (lang) => {
  const buttons = document.querySelectorAll('[data-lang-btn]');
  buttons.forEach((button) => {
    const buttonLang = button.getAttribute('data-lang-btn');
    button.classList.toggle('active', buttonLang === lang);
  });
  document.documentElement.lang = lang === 'en' ? 'en-US' : 'pt-BR';
};

window.initLanguageSwitcher = initLanguageSwitcher;
